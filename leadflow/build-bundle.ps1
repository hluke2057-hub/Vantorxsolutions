# VantorX LeadFlow - single-file bundle builder
# Concatenates all ES modules into one classic script so the app runs
# from a single HTML file (preview servers, file://, email attachments).
# Usage: powershell -ExecutionPolicy Bypass -File build-bundle.ps1
# Re-run after editing any js/*.js file.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path

$files = @(
  'js/utils.js',
  'js/services.js',
  'js/components.js',
  'js/store.js',
  'js/pages/dashboard.js',
  'js/pages/leads.js',
  'js/pages/profile.js',
  'js/pages/pipeline.js',
  'js/pages/automations.js',
  'js/pages/insights.js',
  'js/pages/config.js',
  'js/app.js'
)

function Strip-Imports([string]$text) {
  # remove: import { a, b } from '...';   /   import x from '...';   /   import '...';
  $text = [regex]::Replace($text, '(?m)^import\s+(?:[\w*{},\s]+\s+from\s+)?[''"][^''"]+[''"];?\s*', '')
  # convert: export function x( / export async function x(  ->  function x(
  $text = [regex]::Replace($text, '(?m)^export\s+(async\s+)?(function|const|let|class)\s+', '$1$2 ')
  # convert: export { a, b };  ->  (removed)
  $text = [regex]::Replace($text, '(?m)^export\s*\{[^}]*\};?\s*', '')
  # convert: export default x; -> (removed)
  $text = [regex]::Replace($text, '(?m)^export\s+default\s+[^;]+;\s*', '')
  return $text
}

# NOTE: modules are concatenated at TOP LEVEL (no IIFE wrappers) so that
# cross-module references keep working, exactly as ES module imports did.
# All top-level names across leadflow/js are unique by convention.

$combined = New-Object System.Text.StringBuilder
[void]$combined.AppendLine("/* === VantorX LeadFlow bundled build - generated by build-bundle.ps1 === */")
[void]$combined.AppendLine("/* === Edit the source files in leadflow/js/ then rebuild. === */")

# Alias shims: modules import names with `as` aliases; provide canonical aliases globally.
$aliasShim = @'

/* -- alias shims for bundled build -- */
var esc = escapeHTML;
window.__lf_aliasShims = true;

'@
[void]$combined.AppendLine($aliasShim)

foreach ($f in $files) {
  $path = Join-Path $root $f
  if (-not (Test-Path $path)) { throw "Missing source file: $f" }
  $src = Get-Content $path -Raw -Encoding UTF8
  $stripped = Strip-Imports $src
  [void]$combined.AppendLine("/* ---- $f ---- */")
  [void]$combined.AppendLine($stripped)
  [void]$combined.AppendLine("")
}

$js = $combined.ToString()
$skeletonPath = Join-Path $root 'index.skeleton.html'
if (-not (Test-Path $skeletonPath)) {
  $skeletonPath = Join-Path $root 'index.html'
}
$html = Get-Content $skeletonPath -Raw -Encoding UTF8

# Replace the module script tag with the bundled inline script (classic, no modules)
# Use literal .Replace (no regex) because the JS code contains $ chars.
$pattern = '<script type="module" src="js/app.js"></script>'
$replacement = '<script>' + $js + '</script>'
$newHtml = $html.Replace($pattern, $replacement)

if ($newHtml -eq $html) { throw "Bundle failed: module script tag not found in skeleton HTML" }

$targets = @(
  (Join-Path $root 'leadflow-app.html'),
  (Join-Path $root 'index.html'),
  (Join-Path (Resolve-Path (Join-Path $root '..\website\leadflow')).Path 'leadflow-app.html'),
  (Join-Path (Resolve-Path (Join-Path $root '..\website\leadflow')).Path 'index.html')
)

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
foreach ($t in $targets) {
  [System.IO.File]::WriteAllText($t, $newHtml, $utf8NoBom)
  Write-Host "Bundled -> $t ($([math]::Round((Get-Item $t).Length/1kb)) KB)"
}

