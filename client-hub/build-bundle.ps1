# VantorX Client Hub - single-file bundle builder
# Concatenates all ES modules into one classic script so the app runs
# from a single HTML file (preview servers, file://, email attachments).
# Usage: powershell -ExecutionPolicy Bypass -File build-bundle.ps1
# Re-run after editing any js/*.js file.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path

$files = @(
  'js/utils.js',
  'js/live.js',
  'js/state.js',
  'js/services/notificationService.js',
  'js/services/callService.js',
  'js/services/appointmentService.js',
  'js/services/leadflowService.js',
  'js/services/aiReceptionistService.js',
  'js/services/requestService.js',
  'js/services/billingService.js',
  'js/components.js',
  'js/pages/home.js',
  'js/pages/ai.js',
  'js/pages/calls.js',
  'js/pages/appointments.js',
  'js/pages/leadflow.js',
  'js/pages/activity.js',
  'js/pages/requests.js',
  'js/pages/settings.js',
  'js/pages/onboarding.js',
  'js/app.js'
)

function Resolve-NsImport([string]$modPath, [string]$srcRel) {
  # Resolve one namespace import to its absolute module path + export name list.
  $srcDir = Split-Path -Parent $srcRel
  if (-not $srcDir) { $srcDir = '.' }
  $modFile = Join-Path $root (Join-Path $srcDir $modPath)
  if (-not (Test-Path $modFile)) { $modFile = Join-Path $root $modPath }
  if (-not (Test-Path $modFile)) { throw "Namespace import target not found: $modPath (from $srcRel)" }
  $resolved = (Resolve-Path $modFile).Path
  $modSrc = Get-Content $modFile -Raw -Encoding UTF8
  $names = [regex]::Matches($modSrc, '(?m)^export\s+(?:async\s+)?(?:function|const|let|class)\s+(\w+)') | ForEach-Object { $_.Groups[1].Value }
  [pscustomobject]@{ Path = $resolved; Literal = (($names | ForEach-Object { "$_`: $_" }) -join ', ') }
}

function Strip-Imports([string]$text, [string]$srcRel, [System.Collections.Hashtable]$nsShims) {
  # 1) namespace imports:  import * as S from '../state.js'
  #    Recorded once globally in $nsShims (deduped) — stripped from the file body.
  $nsMatches = [regex]::Matches($text, '(?m)^import\s+\*\s+as\s+(\w+)\s+from\s+[''"]([^''"]+)[''"];?\s*')
  foreach ($m in $nsMatches) {
    $alias = $m.Groups[1].Value
    $modPath = $m.Groups[2].Value
    $resolved = Resolve-NsImport $modPath $srcRel
    if ($nsShims.ContainsKey($alias)) {
      if ($nsShims[$alias].Module -ne $resolved.Path) { throw "Alias '$alias' used for two different modules" }
    } else {
      $nsShims[$alias] = @{ Module = $resolved.Path; Literal = $resolved.Literal }
    }
    $text = $text.Replace($m.Value, '')
  }

  # 2) remove remaining import statements
  $text = [regex]::Replace($text, '(?m)^import\s+(?:[\w*{},\s]+?\s+from\s+)?[''"][^''"]+[''"];?\s*', '')

  # 3) convert: export function x(  ->  function x(
  $text = [regex]::Replace($text, '(?m)^export\s+(async\s+)?(function|const|let|class)\s+', '$1$2 ')
  return $text
}

# NOTE: modules are concatenated at TOP LEVEL (no IIFE wrappers) so that
# cross-module references keep working, exactly as ES module imports did.
# All top-level names across client-hub/js are unique by convention.

$combined = New-Object System.Text.StringBuilder
[void]$combined.AppendLine("/* === VantorX Client Hub bundled build - generated by build-bundle.ps1 === */")
[void]$combined.AppendLine("/* === Edit the source files in client-hub/js/ then rebuild. === */")

$nsShims = @{}

# Pass 1: discover all namespace imports so shims can be emitted FIRST
# (they must exist before any top-level code references them).
foreach ($f in $files) {
  $src = Get-Content (Join-Path $root $f) -Raw -Encoding UTF8
  foreach ($m in [regex]::Matches($src, '(?m)^import\s+\*\s+as\s+(\w+)\s+from\s+[''"]([^''"]+)[''"];?\s*')) {
    $alias = $m.Groups[1].Value
    $modPath = $m.Groups[2].Value
    $resolved = Resolve-NsImport $modPath $f
    if (-not $nsShims.ContainsKey($alias)) {
      $nsShims[$alias] = @{ Module = $resolved.Path; Literal = $resolved.Literal }
    }
  }
}

$shimText = ($nsShims.GetEnumerator() | Sort-Object Name | ForEach-Object {
  "const $($_.Name) = { $($_.Value.Literal) };"
}) -join "`n"

# Pass 2: strip imports and append module bodies.
# Shims are emitted just before the FINAL file (js/app.js) — after every
# module's exports are defined, but before app.js's top-level ctx object
# reads them. (No earlier: shims reference utils/state exports.)
foreach ($f in $files) {
  $path = Join-Path $root $f
  if (-not (Test-Path $path)) { throw "Missing source file: $f" }
  $src = Get-Content $path -Raw -Encoding UTF8
  $stripped = Strip-Imports $src $f $nsShims
  if ($shimText -and $f -eq 'js/app.js') {
    [void]$combined.AppendLine("/* -- namespace shims (deduped) -- */")
    [void]$combined.AppendLine($shimText)
    [void]$combined.AppendLine("")
  }
  [void]$combined.AppendLine("/* ---- $f ---- */")
  [void]$combined.AppendLine($stripped)
  [void]$combined.AppendLine("")
}

$js = $combined.ToString()
$html = Get-Content (Join-Path $root 'index.html') -Raw -Encoding UTF8

# Replace the module script tag with the bundled inline script (classic, no modules)
# Use literal .Replace (no regex) because the JS code contains $ chars.
$pattern = '<script type="module" src="js/app.js"></script>'
$replacement = '<script>' + $js + '</script>'
$newHtml = $html.Replace($pattern, $replacement)

if ($newHtml -eq $html) { throw "Bundle failed: module script tag not found in index.html" }

$outPath = Join-Path $root 'client-hub-app.html'
[System.IO.File]::WriteAllText($outPath, $newHtml, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Bundled $($files.Count) modules -> client-hub-app.html ($([math]::Round((Get-Item $outPath).Length/1kb)) KB)"
